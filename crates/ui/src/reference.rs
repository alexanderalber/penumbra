/// Families in the order of the add dialog; any other family follows alphabetically.
const FAMILIES: &[&str] = &["tex", "chan", "table", "geo", "mat", "light", "view", "script", "out", "comp"];

const HEADER: &str = "<!-- Generated by `cargo xtask docs` from the code; do not edit by hand. -->";

fn family(kind: &str) -> &str {
    kind.split_once('.').map_or(kind, |(f, _)| f)
}

fn families(types: &NodeTypes) -> Vec<String> {
    let mut found: Vec<String> = types.kinds().map(|k| family(k).to_string()).collect();
    found.sort();
    found.dedup();
    let mut ordered: Vec<String> =
        FAMILIES.iter().filter(|f| found.iter().any(|g| g == *f)).map(|f| f.to_string()).collect();
    ordered.extend(found.into_iter().filter(|f| !FAMILIES.contains(&f.as_str())));
    ordered
}

/// The id of the section that holds the component ports.
const PORTS: &str = "component-ports";

/// A section of the node reference: a family, or the component ports of every family together.
struct Section<'a> {
    /// The anchor: the family's name, or [`PORTS`].
    id: String,
    title: String,
    /// The kinds, sorted.
    descs: Vec<&'a NodeDesc>,
}

/// The sections of the node reference: the families in the add dialog's order without their
/// component ports, then the ports of all families under one heading, so `tex.out` does not
/// read as a sink beside `out.video`.
fn sections(types: &NodeTypes) -> Vec<Section<'_>> {
    let sorted = |keep: &dyn Fn(&NodeDesc) -> bool| {
        let mut descs: Vec<&NodeDesc> =
            types.kinds().filter_map(|k| types.desc(k)).filter(|d| keep(d)).collect();
        descs.sort_by(|a, b| a.kind.cmp(&b.kind));
        descs
    };
    let fams = families(types);
    let mut out: Vec<Section<'_>> = fams
        .iter()
        .map(|fam| Section {
            descs: sorted(&|d| family(&d.kind) == fam && d.port.is_none()),
            title: fam.clone(),
            id: fam.clone(),
        })
        .filter(|s| !s.descs.is_empty())
        .collect();
    let mut ports = sorted(&|d| d.port.is_some());
    // By family in the order above, the input before the output.
    let rank = |d: &NodeDesc| fams.iter().position(|f| f == family(&d.kind));
    ports.sort_by_key(|d| (rank(d), d.port != Some(PortRole::In), d.kind.clone()));
    if !ports.is_empty() {
        out.push(Section { id: PORTS.into(), title: "Component ports".into(), descs: ports });
    }
    out
}

/// What the reference says above the component ports.
const PORTS_INTRO: &str = "The input and output sockets of a component, one pair per data kind. They sit inside a \
    `comp.base`. Whatever is wired to the component's socket outside comes out of its `in` node inside. Whatever is \
    wired into an `out` node inside comes out of the component's socket. Grouping nodes into a component adds the \
    ports where wires cross its edge.";

/// Text for a markdown table cell: one line, single spaces, no stray column separators.
fn cell(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ").replace('|', "\\|")
}

fn param_range(spec: &ParamSpec) -> String {
    match spec.range {
        Some(r) if !r.hard => format!("{} (soft)", spec.range_label()),
        _ => spec.range_label(),
    }
}

fn param_default(spec: &ParamSpec) -> String {
    if spec.default.as_str().is_some_and(|t| t.contains('\n')) {
        return "an example script".into();
    }
    let text = spec.default.to_string();
    if text == "\"\"" {
        return String::new();
    }
    let special = spec.default.as_f64().and_then(|v| spec.special_of(v));
    match special {
        Some(s) => format!("`{}` ({})", text.replace('`', "'"), s.label),
        None => format!("`{}`", text.replace('`', "'")),
    }
}

/// What sets a node kind apart, in sentences: time, state, eager cooking, components.
fn node_notes(desc: &NodeDesc) -> Vec<String> {
    let mut notes = Vec::new();
    if desc.time_dependent {
        notes.push("Follows the show clock: cooks again whenever time moves.".to_string());
    }
    if desc.stateful {
        notes.push(
            "Keeps state from frame to frame. `node.reset`, the reset button or R starts the node over."
                .to_string(),
        );
    }
    if desc.eager {
        notes.push(
            "Cooks in every frame, whether anything shows it or not, so it sees every change of its params."
                .to_string(),
        );
    }
    if desc.container {
        notes.push("Holds nodes of its own (a component).".to_string());
    }
    match desc.port {
        Some(PortRole::In) => notes.push("Inside a component: one of its inputs.".to_string()),
        Some(PortRole::Out) => notes.push("Inside a component: one of its outputs.".to_string()),
        None => {}
    }
    if desc.extra_params {
        notes.push("Declares further params per node, from its file or code.".to_string());
    }
    notes
}

/// What the reference says about a run of `len` inputs ([`penumbra_graph::InputRun`]).
pub(crate) fn run_note(len: usize) -> String {
    format!("Any number, up to {len}: each one wired adds a free slot below it")
}

fn node_section(out: &mut String, desc: &NodeDesc) {
    let _ = writeln!(out, "### {}\n\n{}\n", desc.kind, desc.summary);
    let notes = node_notes(desc);
    if !notes.is_empty() {
        let _ = writeln!(out, "{}\n", notes.join(" "));
    }
    if desc.inputs.is_empty() {
        let _ = writeln!(out, "Inputs: none.\n");
    } else {
        let _ = writeln!(out, "Inputs:\n");
        for i in desc.listed_inputs() {
            let previous = if i.previous { " Sees the previous frame, so it may close a loop." } else { "" };
            let run = i.run.map_or(String::new(), run_note);
            let doc = match (i.doc.is_empty(), run.is_empty()) {
                (true, true) => String::new(),
                (true, false) => format!(": {run}"),
                (false, true) => format!(": {}", i.doc),
                (false, false) => format!(": {}. {run}", i.doc.trim_end_matches('.')),
            };
            let _ = writeln!(out, "- `{}` ({}){doc}{previous}", i.name, kind_name(i.kind));
        }
        out.push('\n');
    }
    if desc.outputs.is_empty() {
        let _ = writeln!(out, "Outputs: none.\n");
    } else if desc.outputs.iter().all(|o| o.doc.is_empty()) {
        let list: Vec<String> =
            desc.outputs.iter().map(|o| format!("`{}` ({})", o.name, kind_name(o.kind))).collect();
        let _ = writeln!(out, "Outputs: {}.\n", list.join(", "));
    } else {
        let _ = writeln!(out, "Outputs:\n");
        for o in &desc.outputs {
            let doc = if o.doc.is_empty() { String::new() } else { format!(": {}", o.doc) };
            let _ = writeln!(out, "- `{}` ({}){doc}", o.name, kind_name(o.kind));
        }
        out.push('\n');
    }
    if desc.params.is_empty() {
        return;
    }
    let _ = writeln!(out, "| param | type | default | range | meaning |\n|---|---|---|---|---|");
    for p in &desc.params {
        let group = if p.group.is_empty() { String::new() } else { format!(" *({})*", p.group) };
        let _ = writeln!(
            out,
            "| `{}`{group} | {} | {} | {} | {} |",
            p.name,
            cell(&p.type_label()),
            cell(&param_default(p)),
            cell(&param_range(p)),
            cell(&p.full_doc())
        );
    }
    out.push('\n');
}

fn nodes_md(types: &NodeTypes) -> String {
    let mut out = format!(
        "{HEADER}\n\n# Node reference\n\nEvery built-in node type with its inputs, outputs and params, by family. \
         A param marked with a group, like *(more)*, sits in that folded section of the param panel. A soft range limits only \
         the slider; typed values outside it are kept. For what the families are for, see \
         [Concepts](../concepts.md).\n\n"
    );
    let sections = sections(types);
    let links: Vec<String> = sections.iter().map(|s| format!("[{}](#{})", s.title, s.id)).collect();
    let _ = writeln!(
        out,
        "Sections: {}
",
        links.join(", ")
    );
    for section in &sections {
        let _ = writeln!(
            out,
            "## {}
",
            section.title
        );
        if section.id == PORTS {
            let _ = writeln!(
                out,
                "{PORTS_INTRO}
"
            );
        }
        let list: Vec<String> =
            section.descs.iter().map(|d| format!("[{}](#{})", d.kind, d.kind.replace('.', ""))).collect();
        let _ = writeln!(
            out,
            "{}
",
            list.join(", ")
        );
        for desc in &section.descs {
            node_section(&mut out, desc);
        }
    }
    out
}

/// Every command with its summary: those without a group (`ping`) first, the groups after them
/// by name.
fn sorted_commands(registry: &Registry) -> Vec<(String, String)> {
    let list = registry.list();
    let mut commands: Vec<(String, String)> = list["commands"]
        .as_array()
        .map(|a| {
            a.iter()
                .map(|c| {
                    let field = |k: &str| c[k].as_str().unwrap_or_default().to_string();
                    (field("id"), field("summary"))
                })
                .collect()
        })
        .unwrap_or_default();
    commands.sort_by_key(|(id, _)| (id.contains('.'), id.clone()));
    commands
}

fn commands_md(registry: &Registry) -> String {
    let mut out = format!(
        "{HEADER}\n\n# Command reference\n\nEvery command of the running app, as `penumbra-cli ctl <command>` \
         or a control-channel request sends it (see [Control](../control.md)). `{{a, b?}}` lists \
         the params, `?` marks optional ones.\n\n"
    );
    let mut group = String::new();
    for (id, summary) in &sorted_commands(registry) {
        let g = id.split_once('.').map_or("general", |(g, _)| g);
        if g != group {
            group = g.to_string();
            let _ = writeln!(out, "\n## {group}\n\n| command | |\n|---|---|");
        }
        let _ = writeln!(out, "| `{id}` | {} |", cell(summary));
    }
    out
}

fn docs_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs")
}

/// Compares `name` under `docs` with `text`, or writes it when blessing.
fn check(name: &str, text: &str) -> Option<String> {
    let file = docs_dir().join(name);
    if std::env::var_os("PENUMBRA_BLESS").is_some() {
        if let Some(dir) = file.parent() {
            std::fs::create_dir_all(dir).unwrap();
        }
        std::fs::write(&file, text).unwrap();
        return None;
    }
    let old = std::fs::read_to_string(&file).unwrap_or_default().replace("\r\n", "\n");
    (old != text).then(|| format!("docs/{name}"))
}

/// The markdown files directly in `dir` by file stem, line endings as `\n`.
fn markdown_files(dir: &std::path::Path) -> std::collections::BTreeMap<String, String> {
    let Ok(entries) = std::fs::read_dir(dir) else { return Default::default() };
    entries
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "md"))
        .filter_map(|p| {
            let stem = p.file_stem()?.to_str()?.to_string();
            Some((stem, std::fs::read_to_string(&p).ok()?.replace("\r\n", "\n")))
        })
        .collect()
}

/// The single-page documentation from the node types, the commands and the markdown in `docs`.
fn penumbra_html(types: &NodeTypes, commands: &[(String, String)]) -> String {
    let mut docs = markdown_files(&docs_dir());
    let readme = docs.remove("README").unwrap_or_default();
    let guides: Vec<html::Guide> = docs.into_iter().map(|(stem, text)| html::Guide { stem, text }).collect();
    let node_pages = markdown_files(&docs_dir().join("nodes"));
    for kind in node_pages.keys() {
        assert!(types.desc(kind).is_some(), "docs/nodes/{kind}.md names no node kind");
    }
    let sources = html::Sources { readme: &readme, guides: &guides, node_pages: &node_pages, commands };
    html::page(types, &sources).unwrap()
}

#[test]
fn reference_docs_are_current() {
    let types = Arc::new(penumbra_ops::builtin_types().unwrap());
    let dir = penumbra_core::scratch::ScratchDir::unborn("ui-reference");
    let session = Arc::new(Session::open(&dir, Arc::clone(&types), &Content::default()).unwrap());
    let engine = Engine::start(session).unwrap();
    let mut registry = penumbra_engine::engine_registry(&engine);
    let (bridge, _requests) = crate::Bridge::new();
    crate::control::register(&mut registry, &bridge);
    let commands = sorted_commands(&registry);
    let stale: Vec<String> = [
        check("reference/nodes.md", &nodes_md(&types)),
        check("reference/commands.md", &commands_md(&registry)),
        check("penumbra.html", &penumbra_html(&types, &commands)),
    ]
    .into_iter()
    .flatten()
    .collect();
    engine.shutdown();
    assert!(
        stale.is_empty(),
        "out of date: {}; run `cargo xtask docs` and look at the diff",
        stale.join(", ")
    );
}
